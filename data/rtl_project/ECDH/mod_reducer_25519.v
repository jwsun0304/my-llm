module mod_reducer_25519 (
    input  wire [509:0] product_in,
    output wire [254:0] reduced_out
);
    // p = 2^255 - 19
    localparam [254:0] P_PRIME = 255'h7FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFED;

    // --------------------------------------------------------
    // 1. 입력 데이터를 상위/하위 255비트로 분할
    // --------------------------------------------------------
    wire [254:0] X_L = product_in[254:0];
    wire [254:0] X_H = product_in[509:255]; // 정확히 255비트

    // --------------------------------------------------------
    // 2. 1차 축소: X_H * 19 연산
    // 19 = 16 + 2 + 1 이므로 시프트 연산으로 쪼개서 덧셈
    // 255비트 * 19 이므로 결과는 최대 260비트 [259:0]
    // --------------------------------------------------------
    wire [259:0] X_H_times_19;
    assign X_H_times_19 = {X_H, 4'd0} + {X_H, 1'd0} + X_H;

    // --------------------------------------------------------
    // 3. 1차 덧셈: X_L + (X_H * 19)
    // 결과는 최대 261비트 [260:0]
    // --------------------------------------------------------
    wire [260:0] sum1;
    assign sum1 = X_L + X_H_times_19;

    // --------------------------------------------------------
    // 4. 2차 축소: sum1이 여전히 2^255보다 클 수 있으므로 한번 더 처리
    // --------------------------------------------------------
    wire [254:0] sum1_L = sum1[254:0];
    wire [5:0]   sum1_H = sum1[260:255]; // 오버플로우된 상위 6비트

    wire [10:0]  sum1_H_times_19;
    assign sum1_H_times_19 = {sum1_H, 4'd0} + {sum1_H, 1'd0} + sum1_H;

    // 결과는 최대 256비트 [255:0]
    wire [255:0] sum2;
    assign sum2 = sum1_L + sum1_H_times_19;

    // --------------------------------------------------------
    // 5. 최종 보정 (Final Subtraction)
    // sum2가 p (2^255 - 19) 이상일 경우 한 번 빼줌
    // --------------------------------------------------------
    assign reduced_out = (sum2 >= P_PRIME) ? (sum2 - P_PRIME) : sum2[254:0];

endmodule